#!/usr/bin/env python3
"""Regenerate assets/nse_holidays.js from the live stack's one NSE calendar.

    python scripts/gen_holidays.py ~/Downloads/Automation/Live/market_calendar.py

Never edit assets/nse_holidays.js by hand: market_calendar.py is the single
source (its docstring explains why a second hand-kept list is dangerous).
Display-only here -- a wrong date only changes the board's status line.
Re-run every January after market_calendar.py is refreshed.
"""
import importlib.util, pathlib, sys

src = pathlib.Path(sys.argv[1]).expanduser()
spec = importlib.util.spec_from_file_location("market_calendar", src)
mc = importlib.util.module_from_spec(spec); spec.loader.exec_module(mc)
year = mc.HOLIDAY_CAL_YEAR
dates = sorted(getattr(mc, f"NSE_HOLIDAYS_{year}"))
out = pathlib.Path(__file__).resolve().parent.parent / "assets" / "nse_holidays.js"
out.write_text(
    "/* GENERATED by scripts/gen_holidays.py from Live/market_calendar.py -- do not edit.\n"
    f"   NSE equity trading holidays {year} (weekday dates only). */\n"
    "window.NSE_HOLIDAYS = new Set([\n"
    + "".join(f"  '{d.isoformat()}',\n" for d in dates)
    + "]);\n")
print(f"wrote {out.name}: {len(dates)} dates for {year}")
